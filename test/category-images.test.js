import assert from "node:assert/strict";
import { test } from "node:test";
import { readFile, readdir } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
process.env.DATABASE_URL="postgresql://test:test@127.0.0.1:1/test";
const {pool}=await import("../src/db.js");
const {listCategories,getSeoCategory}=await import("../src/catalog.js");
const {categoryTiles}=await import("../src/page-content.js");
test("categorías usan fotos de productos visibles y preservan la imagen elegida por el admin",async t=>{
 const db=new PGlite();t.after(()=>db.close());
 const migrations=new URL('../migrations/',import.meta.url);
 for(const file of (await readdir(migrations)).filter(f=>f.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(file,migrations),'utf8'));
 t.mock.method(pool,'query',async(sql,values=[])=>db.query(sql,values));
 const root=(await db.query("INSERT INTO categories(name,slug) VALUES('Sellos','sellos-test') RETURNING id")).rows[0].id;
 const child=(await db.query("INSERT INTO categories(name,slug,parent_id) VALUES('Especiales','especiales-test',$1) RETURNING id",[root])).rows[0].id;
 const product=(await db.query("INSERT INTO products(name,slug,category_id,active,price) VALUES('Sello','sello-test',$1,true,100) RETURNING id",[child])).rows[0].id;
 const current=async()=> (await listCategories()).find(c=>c.id===root);
 assert.equal((await current()).image_url,null);
 await db.query('UPDATE products SET images=$2 WHERE id=$1',[product,JSON.stringify([{url:'https://example.com/sello.webp'}])]);
 assert.equal((await current()).image_url,'https://example.com/sello.webp');
 assert.equal((await getSeoCategory('sellos-test')).image_url,'https://example.com/sello.webp');
 assert.match(categoryTiles([await current()]),/https:\/\/example.com\/sello.webp/);
 await db.query('UPDATE products SET images=$2 WHERE id=$1',[product,JSON.stringify([{url:'https://example.com/nueva.webp'}])]);
 assert.equal((await current()).image_url,'https://example.com/nueva.webp');
 await db.query("UPDATE categories SET image_url='https://example.com/manual.webp' WHERE id=$1",[root]);
 assert.equal((await current()).image_url,'https://example.com/manual.webp');
 await db.query("UPDATE categories SET image_url=NULL WHERE id=$1",[root]);
 await db.query('UPDATE categories SET active=false WHERE id=$1',[child]);
 assert.equal((await listCategories({includeEmpty:true})).find(c=>c.id===root).image_url,null);
 await db.query('UPDATE categories SET active=true WHERE id=$1',[child]);
 await db.query('UPDATE products SET active=false WHERE id=$1',[product]);
 assert.equal((await listCategories({includeEmpty:true})).find(c=>c.id===root).image_url,null);
 await db.query('UPDATE products SET active=true WHERE id=$1',[product]);
 const direct=(await db.query("INSERT INTO products(name,slug,category_id,active,images,price) VALUES('Directo','directo-test',$1,true,$2,100) RETURNING id",[root,JSON.stringify([{url:'https://example.com/directa.webp'}])])).rows[0].id;
 assert.equal((await current()).image_url,'https://example.com/directa.webp');
 await db.query("UPDATE products SET images='[]' WHERE id=$1",[direct]);
 assert.equal((await current()).image_url,'https://example.com/nueva.webp');
 await db.query("UPDATE products SET images='[]' WHERE id=$1",[product]);
 assert.equal((await current()).image_url,null);
});
